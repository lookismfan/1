#include "Vector.h" // Подключаем описание класса Vector и объявленных для него операций.
#include <fstream> // Подключаем файловые потоки для чтения input.txt и записи output.txt.
#include <iostream> // Подключаем стандартный вывод сообщений об ошибках и успешном завершении.
#include <memory> // Подключаем умный указатель unique_ptr для автоматического освобождения обычного массива.
#include <utility> // Подключаем std::move для демонстрации перемещения объектов.

int main() { // Начинаем главную функцию, с которой запускается программа.
    std::ifstream input("input.txt"); // Открываем input.txt в режиме чтения исходных данных.
    std::ofstream output("output.txt"); // Открываем output.txt в режиме записи результатов; файл создастся или перезапишется.
    if (!input || !output) { // Проверяем, что оба файла удалось открыть.
        std::cerr << "Cannot open input.txt or output.txt\n"; // Выводим в поток ошибок сообщение, если файл недоступен.
        return 1; // Завершаем программу с кодом ошибки 1.
    } // Завершаем проверку открытия файлов.

    Vector original; // Создаём пустой объект Vector, вызывая конструктор без параметров.
    if (!(input >> original)) { // Читаем первый вектор через перегруженный >> и проверяем результат чтения.
        std::cerr << "Incorrect input vector\n"; // Сообщаем, что размерность или элементы первого вектора неверные.
        return 1; // Прерываем программу с ошибкой, если ввод первого вектора не удался.
    } // Завершаем проверку первого вектора.

    // Второй операнд по условию задания должен быть обычным массивом, а не объектом Vector.
    const int n = original.size(); // Получаем длину первого вектора; именно столько элементов ожидается во втором массиве.
    std::unique_ptr<double[]> ordinary(n > 0 ? new double[n] : nullptr); // Создаём обычный массив double в динамической памяти под управлением unique_ptr.
    for (int i = 0; i < n; ++i) { // Запускаем цикл чтения второго массива по n элементам.
        if (!(input >> ordinary[i])) { // Пытаемся прочитать очередной элемент массива из input.txt.
            std::cerr << "Incorrect ordinary array\n"; // Выводим сообщение, если в файле недостаточно чисел или они записаны неверно.
            return 1; // Завершаем программу с кодом ошибки при неправильном втором массиве.
        } // Завершаем проверку чтения одного элемента.
    } // Завершаем цикл чтения обычного массива.

    double replacement = 0; // Создаём переменную для нового значения элемента при проверке оператора [].
    if (!(input >> replacement)) { // Считываем значение replacement и проверяем успешность операции.
        std::cerr << "Incorrect replacement value\n"; // Сообщаем об отсутствии или ошибке дополнительного числа в файле.
        return 1; // Завершаем программу с ошибкой при некорректном значении replacement.
    } // Завершаем проверку дополнительного числа.

    Vector fromArray(ordinary.get(), n); // Создаём Vector из обычного массива; get() возвращает адрес массива double*.
    Vector sum = original + ordinary.get(); // Складываем объект Vector и обычный массив через перегруженный оператор + варианта 2.

    output << "Author: Andronov Ivan Alekseevich\n"; // Записываем в выходной файл фамилию, имя и отчество студента.
    output << "Group: IU8-14/6 | Lab 3 | Variant 2 | Part 1\n\n"; // Записываем группу, номер лабораторной, вариант и часть работы.
    output << "Vector read from input.txt: " << original << '\n'; // Выводим исходный объект через перегруженный оператор <<.
    output << "Vector created from ordinary array: " << fromArray << '\n'; // Выводим объект, созданный из обычного массива.
    output << "Sum (Vector + double*): " << sum << '\n'; // Выводим полученный вектор сумм после перегруженного сложения.
    if (sum.size() > 1) { // Убеждаемся, что у суммы есть второй элемент с индексом 1.
        output << "Second element of sum, sum[1]: " << sum[1] << '\n'; // Записываем значение второго элемента, используя перегруженный [].
    } // Завершаем проверку наличия второго элемента.

    // Проверяем, что оператор [] может не только читать, но и изменять элементы.
    Vector edited(sum); // Создаём глубокую копию результата сложения конструктором копирования.
    if (edited.size() > 0) { // Проверяем, что копия имеет хотя бы один элемент.
        edited[0] = replacement; // Изменяем первый элемент копии через [] на считанное значение replacement.
    } // Завершаем проверку непустого вектора.
    output << "Edited copy (edited[0] = " << replacement << "): " << edited << '\n'; // Записываем изменённую копию, чтобы показать работу индексации.
    output << "Original sum after editing its copy: " << sum << "\n\n"; // Выводим исходную сумму повторно, демонстрируя независимость глубокой копии.

    // Проверяем четыре механизма: конструкторы копирования/перемещения и оба оператора присваивания.
    Vector byCopy(original); // Создаём новый вектор как глубокую копию original.
    output << "Copy constructor, new vector: " << byCopy << '\n'; // Выводим данные объекта, созданного конструктором копирования.
    output << "Original after copy construction: " << original << '\n'; // Выводим исходный объект: после копирования его значения не изменились.
    Vector byMove(std::move(byCopy)); // Создаём новый объект перемещением ресурсов из byCopy с помощью std::move.
    output << "Move constructor, destination: " << byMove << '\n'; // Выводим объект-получатель после конструктора перемещения.
    output << "Moved-from vector size: " << byCopy.size() << "\n\n"; // Выводим размер бывшего источника byCopy: после перемещения он равен нулю.

    Vector assignedByCopy; // Создаём пустой вектор, в который затем скопируем содержимое другого объекта.
    assignedByCopy = original; // Вызываем перегруженное копирующее присваивание для существующего объекта.
    output << "Copy assignment, destination: " << assignedByCopy << '\n'; // Записываем содержимое получателя после копирующего присваивания.
    output << "Original after copy assignment: " << original << '\n'; // Показываем, что исходный original не изменился после копирования.
    Vector assignedByMove; // Создаём ещё один пустой вектор для проверки перемещающего присваивания.
    assignedByMove = std::move(assignedByCopy); // Передаём ему массив из assignedByCopy через std::move и оператор перемещающего присваивания.
    output << "Move assignment, destination: " << assignedByMove << '\n'; // Записываем получатель после перемещения.
    output << "Moved-from assigned vector size: " << assignedByCopy.size() << '\n'; // Печатаем нулевой размер объекта, из которого переместили массив.

    std::cout << "Results saved to output.txt\n"; // Выводим в консоль сообщение, что результаты сохранены в output.txt.
    return 0; // Возвращаем 0 — программа успешно завершилась.
} // Завершаем функцию main; автоматически вызываются деструкторы локальных объектов.

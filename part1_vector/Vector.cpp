#include "Vector.h" // Подключаем объявления класса Vector из заголовочного файла.

#include <istream> // Подключаем определения классов входных потоков для оператора >>.
#include <ostream> // Подключаем определения выходных потоков для оператора <<.
#include <stdexcept> // Подключаем стандартные исключения для проверки ошибок.
#include <utility> // Подключаем std::move и std::swap для работы с перемещением и обменом.

namespace { // Начинаем анонимное пространство имён: его содержимое видно только в этом файле.
constexpr int MAX_VECTOR_SIZE = 1000000; // Устанавливаем максимальную допустимую размерность вектора; constexpr — константа времени компиляции.
} // Закрываем анонимное пространство имён.

// Конструктор без параметров создаёт пустой вектор и ничего не выделяет в памяти.
Vector::Vector() : data_(nullptr), n_(0) {} // Инициализируем указатель нулевым адресом, а размерность нулём; тело конструктора пустое.

// Вспомогательный конструктор создаёт массив нужной длины и заполняет его нулями.
Vector::Vector(int n) : data_(nullptr), n_(n) { // Задаём начальные значения полей и начинаем тело конструктора с параметром n.
    if (n < 0 || n > MAX_VECTOR_SIZE) { // Проверяем, что размер не отрицателен и не превышает установленный предел.
        throw std::length_error("Invalid vector size"); // Генерируем исключение, если задана неправильная размерность.
    } // Закрываем проверку неправильной размерности.
    if (n > 0) { // Проверяем, что нужен непустой массив.
        data_ = new double[n]{}; // Выделяем динамическую память под n чисел double; фигурные скобки обнуляют элементы.
    } // Закрываем условие выделения памяти.
} // Завершаем конструктор заданной размерности.

// Конструктор из обычного массива делает глубокую копию всех чисел.
Vector::Vector(const double* source, int n) : Vector(n) { // Вызываем другой конструктор Vector(n), чтобы он выделил необходимую память.
    if (n > 0 && source == nullptr) { // Проверяем, что непустой вектор не создают по нулевому указателю.
        throw std::invalid_argument("Null source array"); // Сообщаем об ошибке: адрес исходного массива отсутствует.
    } // Закрываем проверку исходного указателя.
    for (int i = 0; i < n_; ++i) { // Начинаем цикл по всем элементам исходного массива.
        data_[i] = source[i]; // Копируем элемент с индексом i в собственный динамический массив класса.
    } // Завершаем цикл копирования элементов.
} // Завершаем создание вектора на основе обычного массива.

// При копировании нужно создавать новый массив, иначе два объекта владели бы одной памятью.
Vector::Vector(const Vector& other) : Vector(other.data_, other.n_) {} // Создаём копию, вызывая конструктор из массива с адресом и размером другого вектора.

// Перемещение передаёт владение существующим массивом без копирования его элементов.
Vector::Vector(Vector&& other) noexcept // Объявляем конструктор перемещения; двойной && обозначает rvalue-ссылку.
    : data_(other.data_), n_(other.n_) { // Копируем только адрес массива и размер, но не сами элементы.
    other.data_ = nullptr; // Обнуляем указатель исходного объекта, чтобы его деструктор не удалил переданный массив.
    other.n_ = 0; // Сбрасываем размерность перемещённого объекта до нуля.
} // Завершаем конструктор перемещения.

Vector::~Vector() { // Начинаем деструктор; он автоматически вызывается при уничтожении объекта.
    delete[] data_; // Освобождаем массив, выделенный через new[]; delete[] nullptr тоже безопасен.
} // Завершаем деструктор.

// Копирующее присваивание выполняем методом copy-and-swap: копия плюс обмен ресурсами.
Vector& Vector::operator=(const Vector& other) { // Начинаем оператор присваивания копированием; возвращаем ссылку на текущий вектор.
    if (this != &other) { // Не выполняем копирование при присваивании объекта самому себе.
        Vector temporary(other); // Создаём временную глубокую копию правого операнда.
        std::swap(data_, temporary.data_); // Меняем местами указатели текущего и временного объектов.
        std::swap(n_, temporary.n_); // Меняем местами размеры; временный объект теперь владеет старыми данными текущего.
    } // Завершаем условие; временный объект уничтожится и освободит старый массив.
    return *this; // Возвращаем текущий объект по ссылке, позволяя цепочку присваиваний a = b = c.
} // Завершаем оператор копирующего присваивания.

// Перемещающее присваивание передаёт массив существующему объекту без копирования элементов.
Vector& Vector::operator=(Vector&& other) noexcept { // Начинаем оператор перемещающего присваивания; noexcept гарантирует отсутствие исключений.
    if (this != &other) { // Проверяем, что источник и получатель не являются одним объектом.
        delete[] data_; // Освобождаем прежний динамический массив получателя.
        data_ = other.data_; // Передаём получателю указатель на массив исходного объекта.
        n_ = other.n_; // Передаём получателю размерность исходного объекта.
        other.data_ = nullptr; // Сбрасываем указатель источника после передачи владения массивом.
        other.n_ = 0; // Сбрасываем размерность источника, оставляя его пустым.
    } // Завершаем условие защиты от самоприсваивания.
    return *this; // Возвращаем ссылку на получателя для совместимости с обычным присваиванием.
} // Завершаем оператор перемещающего присваивания.

double& Vector::operator[](int index) { // Определяем оператор [] для неконстантного вектора; он возвращает ссылку на элемент.
    if (index < 0 || index >= n_) { // Проверяем, что индекс находится от нуля до n_-1 включительно.
        throw std::out_of_range("Vector index out of range"); // Выбрасываем исключение, если индекс выходит за пределы массива.
    } // Завершаем проверку границ массива.
    return data_[index]; // Возвращаем сам элемент по ссылке, чтобы можно было писать v[i] = значение.
} // Завершаем неконстантную версию оператора [].

const double& Vector::operator[](int index) const { // Определяем оператор [] для константных объектов, который запрещает изменение элемента.
    if (index < 0 || index >= n_) { // Проверяем индекс на выход за границы массива.
        throw std::out_of_range("Vector index out of range"); // Сообщаем об ошибочном индексе исключением out_of_range.
    } // Завершаем проверку индекса.
    return data_[index]; // Возвращаем константную ссылку на элемент, доступный только для чтения.
} // Завершаем константную версию оператора [].

int Vector::size() const { // Начинаем метод size(), возвращающий размер без изменения полей объекта.
    return n_; // Возвращаем количество элементов вектора.
} // Завершаем метод получения размерности.

// Индивидуальное задание: складываем Vector и обычный массив double той же длины.
Vector operator+(const Vector& left, const double* right) { // Начинаем дружественный оператор +; первый операнд — Vector, второй — указатель на массив.
    if (left.n_ > 0 && right == nullptr) { // Проверяем наличие второго массива при ненулевом размере первого вектора.
        throw std::invalid_argument("Null right array"); // Генерируем исключение при отсутствии обычного массива.
    } // Завершаем проверку второго операнда.
    Vector result(left.n_); // Создаём новый вектор с размерностью первого операнда.
    for (int i = 0; i < left.n_; ++i) { // Проходим циклом по индексам обоих массивов.
        result.data_[i] = left.data_[i] + right[i]; // Складываем два соответствующих элемента и записываем сумму в результат.
    } // Завершаем цикл по элементам.
    return result; // Возвращаем новый вектор с полученными суммами.
} // Завершаем перегрузку операции сложения.

// Для вывода используем формат: сначала число элементов, затем элементы через пробел.
std::ostream& operator<<(std::ostream& out, const Vector& v) { // Начинаем дружественный оператор << для записи объекта Vector в выходной поток.
    out << v.n_; // Выводим количество элементов вектора.
    for (int i = 0; i < v.n_; ++i) { // Проходим по всем элементам вектора в цикле.
        out << ' ' << v.data_[i]; // Записываем пробел, а затем очередное значение элемента.
    } // Завершаем цикл вывода элементов.
    return out; // Возвращаем ссылку на тот же поток для цепочек вывода, например out << v << x.
} // Завершаем оператор потокового вывода.

// При вводе считываем размерность и элементы; при ошибке исходный вектор не меняем.
std::istream& operator>>(std::istream& in, Vector& v) { // Начинаем дружественный оператор >> для чтения вектора из входного потока.
    int n; // Объявляем переменную для размера вектора, который будет прочитан из файла.
    if (!(in >> n)) { // Пытаемся прочитать размер и одновременно проверяем успешность чтения.
        return in; // Возвращаем поток в состоянии ошибки, если прочитать размер не удалось.
    } // Завершаем проверку чтения размерности.
    if (n < 0 || n > MAX_VECTOR_SIZE) { // Проверяем диапазон считанного размера.
        in.setstate(std::ios::failbit); // Устанавливаем бит ошибки потока failbit при неправильной размерности.
        return in; // Возвращаем поток с установленным состоянием ошибки.
    } // Завершаем проверку корректности размера.

    Vector temporary(n); // Создаём временный вектор, чтобы не портить старые данные при ошибочном вводе.
    for (int i = 0; i < n; ++i) { // Начинаем считывание всех n элементов.
        if (!(in >> temporary.data_[i])) { // Пытаемся считать очередное число в элемент временного вектора.
            return in; // Прерываем чтение, если элемент отсутствует или записан неверно.
        } // Завершаем проверку чтения текущего элемента.
    } // Завершаем цикл считывания всех элементов.
    v = std::move(temporary); // Перемещаем успешно прочитанный массив в целевой объект v без копирования чисел.
    return in; // Возвращаем входной поток, позволяя читать несколько значений подряд.
} // Завершаем оператор потокового ввода.

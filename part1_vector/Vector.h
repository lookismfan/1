#ifndef VECTOR_H // Проверяем, что заголовочный файл ещё не подключался, чтобы избежать повторных объявлений.
#define VECTOR_H // Объявляем макрос-защиту: при повторном включении содержимое файла будет пропущено.

#include <iosfwd> // Подключаем предварительные объявления потоков istream и ostream.

// Класс Vector хранит вещественные числа в динамическом массиве.
class Vector { // Начинаем объявление нового пользовательского типа данных Vector.
private: // Закрытые поля и методы доступны самому классу и его друзьям, но не напрямую из main.
    double* data_; // Указатель на динамический массив элементов типа double.
    int n_; // Количество элементов вектора, то есть его размерность.

    // Вспомогательный конструктор, доступный только внутри класса и дружественным функциям.
    explicit Vector(int n); // Объявляем явный конструктор вектора заданной длины; explicit запрещает неявные преобразования из int.

public: // Открываем общедоступный интерфейс класса.
    Vector(); // Объявляем конструктор, создающий пустой вектор.
    Vector(const double* source, int n); // Объявляем конструктор, который копирует элементы обычного массива в новый вектор.
    Vector(const Vector& other); // Объявляем конструктор глубокого копирования существующего вектора.
    Vector(Vector&& other) noexcept; // Объявляем конструктор перемещения; noexcept означает обещание не выбрасывать исключения.
    ~Vector(); // Объявляем деструктор, который освободит память после уничтожения объекта.

    Vector& operator=(const Vector& other); // Объявляем оператор присваивания с копированием данных.
    Vector& operator=(Vector&& other) noexcept; // Объявляем оператор присваивания с перемещением владения массивом.

    double& operator[](int index); // Объявляем оператор индексации для чтения и изменения элементов неконстантного вектора.
    const double& operator[](int index) const; // Объявляем оператор индексации только для чтения элементов константного вектора.
    int size() const; // Объявляем метод получения размерности, который не изменяет объект.

    friend Vector operator+(const Vector& left, const double* right); // Объявляем дружественный оператор сложения Vector и обычного массива double; результатом будет Vector.
    friend std::ostream& operator<<(std::ostream& out, const Vector& v); // Объявляем дружественный оператор вывода вектора в поток или файл.
    friend std::istream& operator>>(std::istream& in, Vector& v); // Объявляем дружественный оператор ввода вектора из потока или файла.
}; // Завершаем объявление класса; после класса в C++ нужна точка с запятой.

#endif // Завершаем защиту от повторного включения заголовочного файла.

#include <iostream> // Подключаем стандартный поток cout для вывода координат на экран.
#include <vector> // Подключаем контейнер std::vector, который будет хранить указатели на объекты обоих классов.

// Базовый класс описывает точку на плоскости с координатами x и y.
class Point2D { // Начинаем описание базового класса Point2D.
protected: // Открываем защищённый раздел: поля доступны базовому и производным классам.
    double x; // Храним координату точки по оси X.
    double y; // Храним координату точки по оси Y.

public: // Открываем общедоступный интерфейс базового класса.
    Point2D(double x, double y) : x(x), y(y) {} // Конструктор записывает переданные x и y в одноимённые поля через список инициализации.

    // Невиртуальный метод демонстрирует статическое связывание через указатель базового класса.
    void printStatic() const { // Объявляем обычный метод вывода координат, который не изменяет объект.
        std::cout << "x=" << x << ", y=" << y; // Выводим две координаты x и y базовой точки.
    } // Завершаем метод статического вывода.

    // Виртуальный метод позволяет вызывать версию производного класса через указатель базового.
    virtual void printDynamic() const { // Объявляем виртуальный метод вывода координат и отмечаем, что он не меняет объект.
        std::cout << "x=" << x << ", y=" << y; // Выводим координаты x и y базовой точки.
    } // Завершаем виртуальный метод вывода базового класса.

    virtual ~Point2D() = default; // Создаём виртуальный деструктор по умолчанию для безопасного удаления через базовый указатель.
}; // Завершаем объявление базового класса Point2D.

// Производный класс описывает трёхмерную точку, добавляя координату z.
class Point3D : public Point2D { // Объявляем Point3D наследником Point2D; public сохраняет доступность открытого интерфейса.
private: // Открываем закрытый раздел полей дочернего класса.
    double z; // Храним дополнительную координату Z.

public: // Открываем общедоступный интерфейс производного класса.
    Point3D(double x, double y, double z) // Объявляем конструктор трёхмерной точки с координатами x, y, z.
        : Point2D(x, y), z(z) {} // Сначала вызываем конструктор базового класса для x и y, затем инициализируем z.

    // Метод с тем же именем скрывает невиртуальный метод базового класса.
    void printStatic() const { // Начинаем метод вывода трёхмерной точки для непосредственного обращения к Point3D.
        Point2D::printStatic(); // Сначала явно вызываем базовый метод, чтобы вывести координаты x и y.
        std::cout << ", z=" << z; // Затем дополнительно выводим новую координату z.
    } // Завершаем невиртуальный метод производного класса.

    // Перекрываем виртуальный метод, чтобы при динамическом связывании печатался и z.
    void printDynamic() const override { // Объявляем переопределение виртуального метода; override проверяет правильность сигнатуры.
        Point2D::printDynamic(); // В первую очередь вызываем базовую реализацию метода для вывода x и y.
        std::cout << ", z=" << z; // Допечатываем координату z, которой нет в базовом классе.
    } // Завершаем виртуальный метод производного класса.
}; // Завершаем объявление класса Point3D.

int main() { // Начинаем главную функцию программы.
    Point2D flat(1, 2); // Создаём объект базового класса: точка (1, 2) на плоскости.
    Point3D spatial(3, 4, 5); // Создаём объект производного класса: точка (3, 4, 5) в пространстве.

    std::cout << "Andronov Ivan Alekseevich | IU8-14/6\n"; // Выводим ФИО студента и учебную группу.
    std::cout << "Lab 3 | Variant 2 | Part 2\n\n"; // Выводим номер лабораторной работы, вариант и номер части.

    std::cout << "Direct calls:\n"; // Выводим заголовок для демонстрации прямых вызовов методов.
    std::cout << "Point2D: "; // Подписываем результат для двумерной точки.
    flat.printStatic(); // Напрямую вызываем метод двумерной точки: печатаются x и y.
    std::cout << '\n'; // Переводим вывод на следующую строку.
    std::cout << "Point3D: "; // Подписываем результат для трёхмерной точки.
    spatial.printStatic(); // Напрямую вызываем метод трёхмерной точки: выводятся x, y и z.
    std::cout << "\n\n"; // Добавляем две новые строки перед следующей демонстрацией.

    // По заданию создаём один вектор указателей на базовый и производный объекты.
    std::vector<Point2D*> points = {&flat, &spatial}; // Помещаем в std::vector адреса обеих точек, преобразуя &spatial к Point2D*.

    std::cout << "Static binding (non-virtual method):\n"; // Выводим заголовок демонстрации статического связывания.
    for (Point2D* point : points) { // Перебираем указатели обоих объектов, рассматривая каждый как Point2D*.
        point->printStatic(); // Вызываем невиртуальный метод: выбор определяется типом указателя Point2D*.
        std::cout << '\n'; // Переводим строку после вывода текущей точки.
    } // Завершаем обход указателей для статического связывания.

    std::cout << "\nDynamic binding (virtual method):\n"; // Выводим заголовок демонстрации динамического связывания.
    for (Point2D* point : points) { // Повторно перебираем те же указатели на двумерную и трёхмерную точки.
        point->printDynamic(); // Вызываем виртуальный метод: выбор определяется реальным типом объекта.
        std::cout << '\n'; // Переводим строку после вывода текущей точки.
    } // Завершаем обход указателей для динамического связывания.
    return 0; // Возвращаем 0 в качестве признака успешного завершения программы.
} // Завершаем main; созданные локальные объекты автоматически уничтожаются.
